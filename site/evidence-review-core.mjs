const REVIEW_STORAGE_KEY = "outremer_evidence_reviews_v1";

export function evidencePathForDocument(docId) {
  return `./evidence/${encodeURIComponent(docId)}.evidence.json`;
}

export function buildEvidenceView(dataset) {
  const objects = Array.isArray(dataset?.objects) ? dataset.objects : [];
  const index = new Map(objects.map(item => [item.id, item]));
  const activities = new Map(
    objects.filter(item => item.type === "activity").map(item => [item.id, item])
  );

  return objects
    .filter(item => ["assertion", "identity_hypothesis"].includes(item.type))
    .map(target => {
      const mention = target.type === "identity_hypothesis"
        ? index.get(target.mention_id)
        : objects.find(item =>
            item.type === "mention"
            && target.passage_ids?.includes(item.passage_id)
            && (!target.object || item.verbatim === target.object));
      const passageIds = target.type === "assertion"
        ? target.passage_ids || []
        : [mention?.passage_id].filter(Boolean);
      const passages = passageIds.map(id => index.get(id)).filter(Boolean);
      const provenance = target.provenance || {};
      const activity = activities.get(provenance.generation_activity_id);
      const candidates = (target.candidates || []).map(candidate => ({
        ...candidate,
        identity: index.get(candidate.identity_id) || null,
      }));
      return {target, mention: mention || null, passages, activity: activity || null, candidates};
    });
}

export function loadReviews(storage = localStorage) {
  try {
    return JSON.parse(storage.getItem(REVIEW_STORAGE_KEY) || "[]");
  } catch {
    return [];
  }
}

export function saveReview(review, storage = localStorage) {
  const reviews = loadReviews(storage);
  reviews.push(review);
  storage.setItem(REVIEW_STORAGE_KEY, JSON.stringify(reviews));
  return reviews;
}

export function reviewState(targetId, storage = localStorage) {
  const history = loadReviews(storage).filter(item => item.target_id === targetId);
  const superseded = new Set(history.map(item => item.supersedes).filter(Boolean));
  const active = history.filter(item => !superseded.has(item.id));
  const actions = new Set(active.map(item => item.action));
  return {
    history,
    active,
    conflict: actions.has("accept") && (
      actions.has("reject") || actions.has("flag")
    ),
  };
}

function appendField(container, label, value) {
  if (value === undefined || value === null || value === "") return;
  const row = document.createElement("div");
  row.className = "evidence-field";
  const heading = document.createElement("strong");
  heading.textContent = `${label}: `;
  row.append(heading, document.createTextNode(String(value)));
  container.append(row);
}

export function renderEvidenceReview(container, dataset, options = {}) {
  const items = buildEvidenceView(dataset);
  container.replaceChildren();
  if (!items.length) {
    container.textContent = "No assertions or identity hypotheses in this artifact.";
    return items;
  }

  for (const item of items) {
    const card = document.createElement("article");
    card.className = "card evidence-card";
    const title = document.createElement("h3");
    title.textContent = `${item.target.type.replaceAll("_", " ")} · ${item.target.id}`;
    card.append(title);
    appendField(card, "Mention", item.mention?.verbatim);
    for (const passage of item.passages) {
      appendField(card, `Source passage (${passage.locator})`, passage.text);
    }
    if (item.target.type === "assertion") {
      appendField(card, "Assertion", `${item.target.predicate} → ${item.target.object}`);
      appendField(card, "Review status", item.target.semantics?.review_status);
    }
    if (item.candidates.length) {
      const list = document.createElement("ul");
      list.className = "evidence-candidates";
      for (const candidate of item.candidates) {
        const row = document.createElement("li");
        const label = candidate.identity?.preferred_label || candidate.identity_id;
        row.textContent = `${label} — ${Math.round((candidate.score || 0) * 100)}%`;
        list.append(row);
      }
      card.append(list);
    }
    appendField(card, "Generated by", item.activity
      ? `${item.activity.agent} (${item.activity.adapter_version || "unversioned"})`
      : null);

    const actions = document.createElement("div");
    actions.className = "evidence-actions";
    const comment = document.createElement("input");
    comment.type = "text";
    comment.placeholder = "Review comment…";
    comment.className = "comment-input";
    for (const action of ["accept", "reject", "flag"]) {
      const button = document.createElement("button");
      button.type = "button";
      button.className = `btn-small evidence-${action}`;
      button.textContent = action;
      button.addEventListener("click", () => {
        const review = {
          id: `review-${Date.now()}-${action}`,
          target_id: item.target.id,
          target_type: item.target.type,
          action,
          reviewer: options.reviewer?.() || "anonymous",
          timestamp: new Date().toISOString(),
          comment: comment.value,
          supersedes: null,
        };
        saveReview(review, options.storage || localStorage);
        const state = reviewState(
          item.target.id, options.storage || localStorage
        );
        status.textContent = state.conflict
          ? `conflict: ${action} recorded`
          : `${action} recorded`;
      });
      actions.append(button);
    }
    const supersede = document.createElement("button");
    supersede.type = "button";
    supersede.className = "btn-small";
    supersede.textContent = "supersede";
    supersede.addEventListener("click", () => {
      const prior = prompt("Prior review ID to supersede");
      if (!prior) return;
      saveReview({
        id: `review-${Date.now()}`,
        target_id: item.target.id,
        target_type: item.target.type,
        action: "supersede",
        reviewer: options.reviewer?.() || "anonymous",
        timestamp: new Date().toISOString(),
        comment: comment.value,
        supersedes: prior,
      }, options.storage || localStorage);
      status.textContent = "prior review superseded";
    });
    actions.append(supersede, comment);
    const status = document.createElement("span");
    status.className = "muted evidence-review-status";
    actions.append(status);
    card.append(actions);
    container.append(card);
  }
  return items;
}

export {REVIEW_STORAGE_KEY};
